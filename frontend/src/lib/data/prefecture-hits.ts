// 制覇マップの当たり判定と、地方ごとの色。
//
// 地図は 1 枚の絵（`$lib/assets/japan-map.png`）で、その上に県ごとの
// 透明な長方形を重ねてリンクにする。
//
// **当たり判定は県の形ではなく、県名の文字に合わせている。**
// 形に合わせると、隣り合う県で当たり判定が重なる（実測で 52 組、
// 最悪は神奈川と静岡が 75%）。押し分けられないうえ、県の端は
// どのみち反応しない。文字に合わせれば重なりは 0 になり、
// 「名前を押す」という分かりやすい操作にもなる。
//
// **座標は画像から実測した。** 目分量で置くと隣の文字に掛かる。
// 文字の濃い画素を拾い、白い縁取りを手がかりに 1 文字ずつ切り出し、
// 横につないで語にまとめ、切り出した画像を目で読んで県に対応づけた。
// 余白は上下左右 6px で、これが重ならない最大値である。
//
// 絵を差し替えたら、この座標も測り直すこと。**絵と座標は一組である。**

