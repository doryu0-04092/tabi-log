// 都道府県制覇マップのマス配置。
//
// **見た目の調整をこのファイルだけで行えるように切り出している。**
// 位置を動かしたくなるのは配置が気に入らないときであり、
// そのたびにコンポーネントを触るのは筋が悪い。
//
// **地理的に正確な地図ではなく、角丸の枠に県名を書いて並べる。**
// 理由は4つ。
//
//   1. ライセンスの問題が構造的に消える。そのまま使える日本地図 SVG は
//      コピーレフトのものしか見つからず、地理データからの変換工程を
//      維持するのも避けたい
//   2. 実際の地図では香川・大阪・東京のタップ領域が数ピクセルしかなく、
//      北海道との差が極端になる。**枠なら全県が同じ操作しやすさになる**
//   3. **県名が読める。** 実形状では関東・近畿が密集しており、
//      形を保つ限り文字が重なる。2026-08-31 に実形状を試して確かめた
//   4. 見たいのは「どこを制覇したか」であり、県境の正確な形ではない
//
// 代償として、「日本地図が塗られていく」という見た目の訴求は実地図より弱い。
//
// ---
//
// **配置の方針**（2026-09-01 に組み直した）
//
// 天気予報などで使われるデフォルメ地図を参考にした。
// 県名を横書きで入れるため、マスは正方形ではなく横長の角丸にする。
//
//   - 北海道は右上に**大きく**置き、左下に小さな突起を付ける
//   - 東北は右上に2列で縦へ
//   - 中部・関東は右下がりの帯に流す
//   - 中国・近畿は左へ伸ばす。**行をずらして重なりを避ける**
//   - 四国は中国の下、九州の右に置く
//   - 沖縄は左下に離して単独で置く
//
// 座標は「マス」単位。col が東へ、row が南へ増える。
// **1マスは県名2文字が入る大きさ。** 3文字の県（北海道・神奈川・
// 和歌山・鹿児島）は width で 1.5 マスに広げる。

export type PrefectureTile = {
	/** JIS X 0401 の都道府県コード。 */
	code: string;
	/** 左からの位置（マス単位）。小数で微調整する。 */
	col: number;
	/** 上からの位置（マス単位）。 */
	row: number;
	/** 幅（マス単位）。省略時は 1。3文字の県だけ 1.5 にする。 */
	width?: number;
	/** 高さ（マス単位）。省略時は 1。北海道だけ大きい。 */
	height?: number;
	/** 左下に突起を付けるか。北海道だけ true。 */
	tail?: boolean;
};

/** マスの基準寸法（px）。SVG の座標系で使う。 */
